import { randomUUID } from "node:crypto";
import { test, expect } from "@playwright/test";

test("registro, login, creación, edición, archivo y cierre de sesión desde la interfaz", async ({ page, context }, testInfo) => {
  const email = `browser-${randomUUID()}@example.test`;
  const password = `Clave de prueba ${randomUUID()}`;
  const subject = `Programación ${testInfo.project.name}`;
  const pageErrors: string[] = [];
  page.on("pageerror", error => pageErrors.push(error.message));
  await page.goto("/materias");
  await expect(page).toHaveURL(/\/login/);
  await page.getByRole("link", { name: "Crea tu cuenta", exact: true }).click();
  await page.getByLabel("Nombre", { exact: true }).fill("Estudiante de prueba");
  await page.getByLabel("Correo electrónico").fill(email);
  await page.getByLabel("Contraseña", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Crear cuenta", exact: true }).click();
  await expect(page).toHaveURL(/\/login\?registro=1/);
  await expect(page.getByRole("status")).toContainText("Tu cuenta está lista");
  await page.getByLabel("Correo electrónico").fill(email);
  await page.getByLabel("Contraseña", { exact: true }).fill("incorrecta");
  await page.getByRole("button", { name: "Iniciar sesión", exact: true }).click();
  await expect(page.locator("form").getByRole("alert")).toContainText("Correo o contraseña incorrectos");
  await page.getByLabel("Contraseña", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Iniciar sesión", exact: true }).click();
  await expect(page).toHaveURL(/\/inicio$/);
  await expect(page.getByRole("heading", { name: "Hola, Estudiante de prueba." })).toBeVisible();
  const session = (await context.cookies()).find(cookie => cookie.name === "siare_session");
  expect(session?.httpOnly).toBe(true);
  expect(session?.sameSite).toBe("Lax");
  expect(await page.evaluate(() => localStorage.length)).toBe(0);
  await page.getByRole("link", { name: "Ir a mis materias" }).click();
  await page.getByRole("link", { name: "Crear mi primera materia" }).click();
  await page.getByLabel("Nombre de la materia").fill(subject);
  await page.getByLabel("Descripción (opcional)").fill("Materia creada y verificada desde el navegador.");
  await page.getByRole("button", { name: "Crear materia", exact: true }).click();
  await expect(page.getByRole("heading", { name: subject, exact: true })).toBeVisible();
  await expect(page.getByLabel("Nombre de la materia")).toHaveValue(subject);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: `../.cache/phase1-workspace-${testInfo.project.name}.png`, fullPage: true });
  await page.getByLabel("Nombre de la materia").fill(`${subject} actualizada`);
  await page.getByRole("button", { name: "Guardar cambios" }).click();
  await expect(page.getByRole("status")).toContainText("Cambios guardados");
  await expect(page.getByRole("heading", { name: `${subject} actualizada`, exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Archivar materia", exact: true }).click();
  await page.getByRole("button", { name: "Confirmar archivo" }).click();
  await expect(page.getByRole("status")).toContainText("Esta materia está archivada");
  await expect(page.getByRole("button", { name: "Guardar cambios" })).toHaveCount(0);
  await page.getByRole("link", { name: "← Mis materias", exact: true }).click();
  await page.getByLabel("Mostrar").selectOption("archived");
  await expect(page.getByRole("link", { name: `${subject} actualizada`, exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Cerrar sesión" }).click();
  await expect(page).toHaveURL(/\/login$/);
  expect((await context.cookies()).some(cookie => cookie.name === "siare_session")).toBe(false);
  await page.goto("/inicio");
  await expect(page).toHaveURL(/\/login/);
  expect(pageErrors).toEqual([]);
});

test("el BFF rechaza operaciones sin protección CSRF y sesiones inválidas", async ({ page, context, baseURL }) => {
  const response = await context.request.post("/api/bff/auth/login", { data: { email: "csrf@example.test", password: "ignored" } });
  expect(response.status()).toBe(403);
  await context.addCookies([{ name: "siare_session", value: "invalid-token", url: baseURL!, httpOnly: true, sameSite: "Lax" }]);
  await page.goto("/inicio");
  await expect(page).toHaveURL(/\/login\?sesion=expirada/);
  await expect(page.getByRole("status")).toContainText("Tu sesión ha caducado");
  await page.goto("/registro");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByLabel("Nombre", { exact: true }).focus();
  await page.keyboard.press("Tab");
  await expect(page.getByLabel("Correo electrónico")).toBeFocused();
});
